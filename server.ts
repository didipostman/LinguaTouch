import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI, Type } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json({ limit: '25mb' }));

// Shared Gemini client
const getGeminiClient = () => {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return null;
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
};

// Health check
app.get('/api/health', (req, res) => {
  res.json({
    status: 'ok',
    hasGeminiKey: Boolean(process.env.GEMINI_API_KEY),
  });
});

// Real-time Text to Speech endpoint
app.post('/api/tts', async (req, res) => {
  try {
    const { text, language, voiceName = 'Kore', speed = 1.0 } = req.body;
    if (!text || typeof text !== 'string') {
      res.status(400).json({ error: 'Text is required' });
      return;
    }

    const ai = getGeminiClient();
    if (!ai) {
      res.status(503).json({ error: 'GEMINI_API_KEY not configured on server' });
      return;
    }

    const validVoice = ['Puck', 'Charon', 'Kore', 'Fenrir', 'Zephyr'].includes(voiceName)
      ? voiceName
      : 'Kore';

    const promptText = `Speak clearly and naturally in ${language || 'the target language'} at normal learner pace: "${text}"`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: promptText,
              speechMetadata: {
                style: 'Clear, encouraging language tutor with authentic native pronunciation',
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: validVoice },
          },
        },
      },
    });

    const candidatePart = response.candidates?.[0]?.content?.parts?.[0];
    const base64Audio = candidatePart?.inlineData?.data;
    const mimeType = candidatePart?.inlineData?.mimeType || 'audio/pcm;rate=24000';

    if (!base64Audio) {
      res.status(500).json({ error: 'No audio generated by TTS model' });
      return;
    }

    res.json({
      audio: base64Audio,
      mimeType,
      sampleRate: 24000,
      voice: validVoice,
    });
  } catch (error: any) {
    console.error('Error generating TTS:', error);
    res.status(500).json({
      error: error?.message || 'Failed to synthesize speech',
    });
  }
});

// Pronunciation evaluation endpoint
app.post('/api/pronunciation-evaluate', async (req, res) => {
  try {
    const {
      targetText,
      targetLanguage,
      phoneticExpected,
      transcript,
      audioBase64,
      audioMimeType = 'audio/webm',
    } = req.body;

    if (!targetText) {
      res.status(400).json({ error: 'Target text is required' });
      return;
    }

    const ai = getGeminiClient();
    if (!ai) {
      // Fallback evaluation if no API key
      const isExact = (transcript || '').trim().toLowerCase() === targetText.trim().toLowerCase();
      const score = isExact ? 95 : Math.max(40, Math.min(85, Math.round(transcript ? 75 : 50)));
      res.json({
        overallScore: score,
        rating: score >= 90 ? 'Excellent' : score >= 75 ? 'Good' : 'Needs Practice',
        phonemeFeedback: [
          {
            part: targetText,
            status: isExact ? 'good' : 'needs-work',
            feedback: isExact
              ? 'Sounded accurate and clear!'
              : `Heard: "${transcript || 'silence'}" — compare with "${targetText}"`,
          },
        ],
        articulatoryTips: 'Ensure clear vowel articulation and relaxed vocal cords.',
        stressFeedback: 'Match natural syllable emphasis.',
        encouragement: 'Keep practicing! Repetition trains your muscle memory.',
      });
      return;
    }

    const systemPrompt = `You are an expert native pronunciation coach and linguist specializing in ${targetLanguage}.
You evaluate a student's spoken pronunciation attempt for the target word/sentence: "${targetText}".
Expected phonetic IPA: "${phoneticExpected || ''}".
The student's automatic speech recognition transcript was: "${transcript || '(no transcript detected)'}".

Assess their audio (if provided) and transcript. Give constructive, phonetically precise feedback.
Return JSON strictly adhering to the schema:
- overallScore: integer 0-100 (accuracy, clarity, cadence)
- rating: "Excellent" (90-100) | "Good" (75-89) | "Fair" (60-74) | "Needs Practice" (<60)
- phonemeFeedback: array of 2-5 segments/syllables of the target word with:
    part: string (e.g. syllable or phoneme "ra", "ble", "ción")
    ipa: string (IPA for that slice)
    status: "good" | "needs-work" | "missed"
    feedback: string (actionable advice on that exact sound)
- articulatoryTips: physical tongue, lip, and breath instructions (e.g., "Place tip of tongue on alveolar ridge behind upper teeth without stopping airflow")
- stressFeedback: note on syllable stress (e.g., "Stress falls on second-to-last syllable")
- encouragement: short inspiring quote or tip for muscle memory.`;

    const contents: any[] = [];
    if (audioBase64) {
      // Use multimodal audio input with gemini-3.8-flash
      contents.push({
        parts: [
          {
            inlineData: {
              data: audioBase64,
              mimeType: audioMimeType,
            },
          },
          {
            text: `Evaluate my spoken pronunciation of: "${targetText}" in ${targetLanguage}. Student recognized transcript: "${transcript || ''}".`,
          },
        ],
      });
    } else {
      contents.push({
        parts: [
          {
            text: `Evaluate student pronunciation attempt for: "${targetText}" in ${targetLanguage}. Student speech transcript: "${transcript || ''}".`,
          },
        ],
      });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents,
      config: {
        systemInstruction: systemPrompt,
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            overallScore: { type: Type.INTEGER },
            rating: { type: Type.STRING },
            phonemeFeedback: {
              type: Type.ARRAY,
              items: {
                type: Type.OBJECT,
                properties: {
                  part: { type: Type.STRING },
                  ipa: { type: Type.STRING },
                  status: { type: Type.STRING },
                  feedback: { type: Type.STRING },
                },
                required: ['part', 'ipa', 'status', 'feedback'],
              },
            },
            articulatoryTips: { type: Type.STRING },
            stressFeedback: { type: Type.STRING },
            encouragement: { type: Type.STRING },
          },
          required: [
            'overallScore',
            'rating',
            'phonemeFeedback',
            'articulatoryTips',
            'stressFeedback',
            'encouragement',
          ],
        },
      },
    });

    const parsed = JSON.parse(response.text?.trim() || '{}');
    res.json(parsed);
  } catch (error: any) {
    console.error('Error evaluating pronunciation:', error);
    res.status(500).json({
      error: error?.message || 'Pronunciation evaluation failed',
    });
  }
});

// AI Deck Generator endpoint
app.post('/api/generate-deck', async (req, res) => {
  try {
    const { language, topic, count = 8, level = 'beginner' } = req.body;
    if (!language || !topic) {
      res.status(400).json({ error: 'Language and topic are required' });
      return;
    }

    const ai = getGeminiClient();
    if (!ai) {
      res.status(503).json({ error: 'GEMINI_API_KEY not configured on server' });
      return;
    }

    const prompt = `Create a custom vocabulary learning deck of exactly ${count} highly useful words or short phrases for learning ${language}.
Topic: "${topic}".
Proficiency Level: ${level}.

Include accurate spelling (with diacritics/accents/characters), standard English translations, IPA phonetic transcriptions, realistic example sentences with English translations, and brief memory/cultural tips.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            title: { type: Type.STRING },
            description: { type: Type.STRING },
            level: { type: Type.STRING },
            items: {
              type: Type.ARRAY,
              items: {
                type: Type.OBJECT,
                properties: {
                  word: { type: Type.STRING, description: 'Target language word or short phrase' },
                  translation: { type: Type.STRING, description: 'English translation' },
                  phonetic: { type: Type.STRING, description: 'Phonetic IPA notation like /o.la/' },
                  exampleTarget: { type: Type.STRING, description: 'Example sentence in target language' },
                  exampleTranslation: { type: Type.STRING, description: 'Example sentence translated to English' },
                  notes: { type: Type.STRING, description: 'Grammar gender or usage tip' },
                  difficulty: { type: Type.STRING, description: 'easy | medium | hard' },
                },
                required: ['word', 'translation', 'phonetic', 'exampleTarget', 'exampleTranslation'],
              },
            },
          },
          required: ['title', 'description', 'items'],
        },
      },
    });

    const parsed = JSON.parse(response.text?.trim() || '{}');
    res.json(parsed);
  } catch (error: any) {
    console.error('Error generating deck:', error);
    res.status(500).json({
      error: error?.message || 'Failed to generate vocabulary deck',
    });
  }
});

// Configure Vite middleware in dev or static serving in production
async function startServer() {
  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  }

  app.listen(Number(PORT), '0.0.0.0', () => {
    console.log(`Server listening on http://0.0.0.0:${PORT} in ${isProd ? 'production' : 'development'} mode`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
